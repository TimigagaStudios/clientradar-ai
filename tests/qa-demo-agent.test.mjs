// Isolated evidence-aware demo helper tests.
import assert from 'node:assert/strict';
import { build } from 'esbuild';
const result = await build({ entryPoints: ['api/lib/_qa-demo-agent.ts'], bundle: true, platform: 'node', format: 'esm', write: false, logLevel: 'silent' });
const { screenEvidenceDemo, evidenceDemoStatus } = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].contents).toString('base64')}`);
const now = new Date('2026-11-17T12:00:00Z');
const site = { status: 'available', checkedAt: now.toISOString(), host: 'business.test', emails: ['team@business.test'], phones: ['+2348005551234'] };
const lead = { business_name: 'Example Business', email: 'team@business.test', phone: '+2348005551234', website: 'https://business.test' };
const demo = { businessName: lead.business_name, hero: { title: ' Welcome ' }, about: { body: 'About' }, services: [{ title: 'One', body: 'Two' }], contact: { email: lead.email, phone: lead.phone }, disclaimer: 'Demo' };
const before = JSON.stringify({ demo, lead, site });
const checked = screenEvidenceDemo(demo, lead, site, { now });
assert.equal(evidenceDemoStatus(checked, lead, now), 'checked');
assert.equal(checked.hero.title, ' Welcome ');
assert.equal(JSON.stringify({ demo, lead, site }), before);
assert(!JSON.stringify(checked.qa.agent).includes('team@business.test'));
assert.equal(evidenceDemoStatus(checked, { ...lead, email: 'changed@business.test' }, now), 'stale');
assert.equal(evidenceDemoStatus({ ...checked, businessName: 'Changed' }, lead, now), 'stale');
assert.equal(evidenceDemoStatus(checked, null, now), 'stale');
assert.equal(evidenceDemoStatus(checked, lead, new Date(now.getTime() + 7 * 86400000 + 1)), 'stale');
assert.equal(evidenceDemoStatus(checked, lead, new Date(now.getTime() - 1)), 'stale');
assert.equal(evidenceDemoStatus(demo, lead, now), 'unchecked');
const optin = screenEvidenceDemo(demo, lead, site, { now, fixWhitespace: true }); assert.equal(optin.hero.title, 'Welcome'); assert.equal(optin.businessName, demo.businessName);
const missingSite = screenEvidenceDemo(demo, lead, { status: 'unavailable', checkedAt: now.toISOString(), host: null, emails: [], phones: [] }, { now });
assert(missingSite.qa.issues.some(x => x.code === 'website_not_checked')); assert.equal(evidenceDemoStatus(missingSite, lead, now), 'checked');
const wrongSite = screenEvidenceDemo(demo, lead, { ...site, host: 'other.test' }, { now });
assert(wrongSite.qa.issues.some(x => x.code === 'website_not_checked')); assert.equal(wrongSite.qa.agent.websiteStatus, 'unavailable'); assert.equal(wrongSite.qa.agent.websiteHost, null);
const sample = screenEvidenceDemo({ ...demo, businessName: 'Other', showcase: { sample: true, items: [{ title: 'Guaranteed' }] } }, lead, site, { now });
for (const code of ['name_differs_from_lead', 'sample_showcase', 'guarantee']) assert(sample.qa.issues.some(x => x.code === code), code);
const absentLead = screenEvidenceDemo(demo, {}, { ...site, status: 'not_provided' }, { now });
assert(absentLead.qa.issues.some(x => x.code === 'lead_identity_missing'));
const withPhotos = { ...demo, photos: [{ kind: 'own', url: 'https://owner.test/image.jpg' }] };
const rights = screenEvidenceDemo(withPhotos, lead, site, { now });
assert(rights.qa.issues.some(x => x.code === 'image_rights_need_review' && x.path === 'photos'));
assert.equal(evidenceDemoStatus(rights, lead, now), 'checked');
assert.deepEqual(rights.photos, withPhotos.photos); // Legacy photos are not removed.
const oldReview = structuredClone(rights); oldReview.qa.issues = oldReview.qa.issues.filter(x => x.code !== 'image_rights_need_review');
assert.equal(evidenceDemoStatus(oldReview, lead, now), 'stale');
const unknown = screenEvidenceDemo({ ...demo, photos: [{ url: 'https://owner.test/unknown.jpg' }] }, lead, site, { now });
assert(unknown.qa.issues.some(x => x.code === 'image_rights_need_review'));
const samples = screenEvidenceDemo({ ...demo, photos: [{ kind: 'sample', url: 'https://images.pexels.com/example.jpg' }] }, lead, site, { now });
assert(!samples.qa.issues.some(x => x.code === 'image_rights_need_review'));
assert.equal(evidenceDemoStatus(samples, lead, now), 'checked');
console.log('PASS isolated demo evidence freshness, content and lead binding, conservative missing evidence, opt-in and privacy. Helper-only test.');
